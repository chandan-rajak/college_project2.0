/* ================= LOAD DEPARTMENT ================= */

function loadDepartment(dept) {

  const data = departmentData[dept];

  deptName.textContent = data.name;
  about.textContent = data.about;
  vision.textContent = data.vision;
  hod.textContent = data.hod;
  placement.textContent = data.placement;
  contactInfo.textContent = data.contact;

  /* ===== FACULTY ===== */

  facultyContainer.innerHTML = "";

  data.faculty.forEach(faculty => {

    facultyContainer.innerHTML += `
      <div class="faculty-card">
        <img src="${faculty.image}">
        <h3>${faculty.name}</h3>
        <p>${faculty.designation}</p>
        <p>${faculty.qualification}</p>
        <p>${faculty.specialization}</p>
        <p>${faculty.experience}</p>
        <p>${faculty.email}</p>
      </div>
    `;
  });

  /* ===== SUBJECTS ===== */


  subjects.innerHTML = "";

  Object.keys(data.subjects).forEach((semester, index) => {

    const semesterSubjects = data.subjects[semester];

    subjects.innerHTML += `

    <div class="semester-box">

      <button class="semester-btn">
        ${semester}
        <span>▼</span>
      </button>

      <div class="semester-subjects">

        ${semesterSubjects.map(subject => `
          <div class="subject-card">
            <h3>${subject}</h3>
          </div>
        `).join("")}

      </div>

    </div>

  `;
  });

  /* ===== ACCORDION ===== */

  const semesterButtons =
    document.querySelectorAll(".semester-btn");

  semesterButtons.forEach(button => {

    button.addEventListener("click", () => {

      const parent =
        button.parentElement;

      parent.classList.toggle("active");

    });

  });

  /* ===== LABS ===== */


  labsContainer.innerHTML = "";

  Object.keys(data.labs).forEach((semester) => {

    const semesterLabs = data.labs[semester];

    labsContainer.innerHTML += `

    <div class="lab-semester-box">

      <button class="lab-semester-btn">
        ${semester}
        <span>▼</span>
      </button>

      <div class="lab-semester-content">

        ${semesterLabs.map(lab => `
          <div class="lab-card">
            <i class="fa-solid fa-flask"></i>
            <h3>${lab}</h3>
          </div>
        `).join("")}

      </div>

    </div>

  `;
  });

  /* ===== LAB ACCORDION ===== */

  const labButtons =
    document.querySelectorAll(".lab-semester-btn");

  labButtons.forEach(button => {

    button.addEventListener("click", () => {

      const parent =
        button.parentElement;

      parent.classList.toggle("active");

    });

  });

  /* ===== STUDENT ===== */

  studentInfo.innerHTML = "";

  data.student.forEach(item => {

    studentInfo.innerHTML += `
      <div class="student-card">
        <h3>${item}</h3>
      </div>
    `;
  });

  /* ===== ACHIEVEMENTS ===== */

  achievements.innerHTML = "";

  data.achievements.forEach(item => {

    achievements.innerHTML += `
      <div class="achievement-card">
        <h3>${item}</h3>
      </div>
    `;
  });

  /* ===== GALLERY ===== */

  currentGallery = data.gallery;
  currentIndex = 0;
  galleryImage.src = currentGallery[currentIndex];
}

/* ================= BUTTON EVENTS ================= */

deptButtons.forEach(button => {

  button.addEventListener("click", () => {

    deptButtons.forEach(btn => btn.classList.remove("active"));

    button.classList.add("active");

    loadDepartment(button.dataset.dept);

  });

});

/* ================= GALLERY ================= */

document.getElementById("nextBtn").addEventListener("click", () => {

  currentIndex = (currentIndex + 1) % currentGallery.length;

  galleryImage.src = currentGallery[currentIndex];

});

document.getElementById("prevBtn").addEventListener("click", () => {

  currentIndex =
    (currentIndex - 1 + currentGallery.length)
    % currentGallery.length;

  galleryImage.src = currentGallery[currentIndex];

});

